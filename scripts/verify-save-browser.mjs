// Optional browser check: use an existing Playwright installation, not a new game dependency.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import { build } from 'esbuild';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const helper = await build({ stdin: { contents: "export { localGameRepository as repo } from './src/storage/LocalGameRepository'; export { createInitialGameState as initial } from './src/storage/GameRepository';", resolveDir: process.cwd(), loader: 'ts' }, bundle: true, write: false, format: 'iife', globalName: 'transferFixture', platform: 'browser' });
const child = spawn(process.execPath, ['dist-web/server.mjs'], { env: { ...process.env, PORT: '18173', NODE_ENV: 'production' }, stdio: ['ignore', 'pipe', 'pipe'] });
const exited = once(child, 'exit');
let browser;
try {
  await once(child.stdout, 'data');
  browser = await chromium.launch({ ...(process.env.BROWSER_CHANNEL ? { channel: process.env.BROWSER_CHANNEL } : {}), headless: true });
  const context = await browser.newContext({ serviceWorkers: 'block' });
  await context.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
  const page = await context.newPage();
  await page.goto('http://127.0.0.1:18173/api/health');
  await page.addScriptTag({ content: helper.outputFiles[0].text });
  const result = await page.evaluate(async () => {
    const { repo, initial } = transferFixture;
    const original = initial('Browser synthetic destination');
    await repo.save(original);
    const exported = await repo.export();
    const incoming = JSON.parse(exported);
    incoming.gameState.player.displayName = 'Browser synthetic incoming';
    incoming.extraSaves.quan_lo_air_combat_v1 = '{"version":1,"synthetic":true}';
    await repo.import(JSON.stringify(incoming));
    const db = await new Promise((resolve, reject) => { const r = indexedDB.open('quan_lo_db', 1); r.onsuccess = () => resolve(r.result); r.onerror = () => reject(); });
    const idb = await new Promise((resolve, reject) => { const r = db.transaction('game_state', 'readonly').objectStore('game_state').get('current'); r.onsuccess = () => resolve(r.result); r.onerror = () => reject(); });
    db.close();
    const archiveKey = Object.keys(localStorage).find(k => k.startsWith('quan_lo_import_archive_'));
    const archive = JSON.parse(localStorage.getItem(archiveKey));
    await repo.save(original);
    return { idbName: JSON.parse(idb).player.displayName, lsName: JSON.parse(localStorage.getItem('quan_lo_game_state_v1')).player.displayName, archivedIdb: JSON.parse(archive.indexedDB).player.displayName, sideSave: localStorage.getItem('quan_lo_air_combat_v1') };
  });
  assert.equal(result.idbName, 'Browser synthetic incoming');
  assert.equal(result.lsName, 'Browser synthetic incoming');
  assert.equal(result.archivedIdb, 'Browser synthetic destination');
  assert.ok(result.sideSave.includes('synthetic'));
  console.log('PASS browser real IndexedDB import transaction/archive and autosave guard');
  await context.close();
  const ui = await browser.newContext({ viewport: { width: 430, height: 932 }, serviceWorkers: 'block', acceptDownloads: true });
  const blocked = [];
  await ui.route('**/*', route => { if (new URL(route.request().url()).hostname === '127.0.0.1') return route.continue(); blocked.push(route.request().url()); return route.abort(); });
  const view = await ui.newPage();
  await view.goto('http://127.0.0.1:18173/api/health');
  await view.addScriptTag({ content: helper.outputFiles[0].text });
  const version = JSON.parse(await readFile('dist-web/client/version.json', 'utf8'));
  await view.evaluate(buildId => { const state = transferFixture.initial('UI synthetic player'); state.ui.onboardingCompleted = true; state.settings.notificationsEnabled = false; localStorage.setItem('quan_lo_game_state_v1', JSON.stringify(state)); localStorage.setItem('quan_lo_installed_build_v1', JSON.stringify({ buildId, activatedAt: Date.now() })); }, version.buildId);
  await view.goto('http://127.0.0.1:18173/');
  await view.getByTitle('Mở Hồ Sơ & Cài Đặt', { exact: true }).click();
  await view.getByText('Xuất Dữ Liệu', { exact: true }).waitFor();
  const downloadPromise = view.waitForEvent('download');
  await view.getByText('Xuất Dữ Liệu', { exact: true }).click();
  const download = await downloadPromise;
  assert.match(download.suggestedFilename(), /^quan-lo-save-.*\.json$/);
  const contents = JSON.parse(await readFile(await download.path(), 'utf8'));
  assert.equal(contents.gameState.player.displayName, 'UI synthetic player');
  contents.gameState.player.displayName = 'UI imported player';
  await view.getByText('Nhập Dữ Liệu', { exact: true }).click();
  await view.getByLabel('Chọn file save Quân Lộ').setInputFiles({ name: 'synthetic.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(contents)) });
  view.once('dialog', dialog => dialog.accept());
  await Promise.all([view.waitForEvent('framenavigated'), view.getByText('Xác Nhận Nhập', { exact: true }).click()]);
  await view.waitForFunction(() => JSON.parse(localStorage.getItem('quan_lo_game_state_v1')).player.displayName === 'UI imported player');
  assert.ok(!blocked.some(url => url.includes('quan-lo-push-api')));
  console.log('PASS browser UI download/file import/confirmation/reload, no legacy Push request');
  await ui.close();
} finally { await browser?.close(); child.kill('SIGTERM'); await exited; }
