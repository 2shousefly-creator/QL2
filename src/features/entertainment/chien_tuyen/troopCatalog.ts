/** Readable keyed alias used by UI and simulation code. */
export const TROOP_BY_TYPE = TROOP_CATALOG;

export const TROOP_CATALOG_LIST: readonly TroopDefinition[] = TROOP_TYPES.map(
  (troopType) => TROOP_CATALOG[troopType]
);

export function isTroopType(value: unknown): value is TroopType {
  return typeof value === "string" && (TROOP_TYPES as readonly string[]).includes(value);
}

export function getTroopDefinition(troopType: TroopType): TroopDefinition {
  return TROOP_CATALOG[troopType];
}

export function getTroopStats(troopType: TroopType, level: number): TroopStats {
  const definition = getTroopDefinition(troopType);
  const safeLevel = clampTroopLevel(level);
  const levelOffset = safeLevel - 1;
  return {
    maxHp: definition.baseStats.maxHp + definition.growth.maxHp * levelOffset,
    attack: definition.baseStats.attack + definition.growth.attack * levelOffset,
    defense: definition.baseStats.defense + definition.growth.defense * levelOffset,
    critChance: definition.baseStats.critChance,
    speed: definition.baseStats.speed,
  };
}
