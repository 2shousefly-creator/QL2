import { Graphics } from 'pixi.js';
// Original vector silhouettes used by pooled effects and oriented projectiles.
export function drawMotif(g: Graphics, kind: string, color: number, accent: number, phase = 0) {
  const line=(points:number[],width=3,c=accent)=>g.poly(points,false).stroke({color:c,width,cap:'round',join:'round'});
  const ring=(r:number,c=accent,w=3)=>g.circle(0,0,r).stroke({color:c,width:w});
  const shard=(x:number,y:number,s=1)=>g.poly([x,y-24*s,x+9*s,y,x,y+12*s,x-9*s,y]).fill(color).stroke({color:accent,width:1});
  const rays=(n:number,r:number,len:number)=>{for(let i=0;i<n;i++){const a=i/n*Math.PI*2;line([Math.cos(a)*r,Math.sin(a)*r,Math.cos(a)*(r+len),Math.sin(a)*(r+len)],2);}};
  const arc=(r:number,start=-2.3,end=.7,w=6)=>g.arc(0,0,r,start,end).stroke({color:accent,width:w,cap:'round'});
  const slash=()=>{g.poly([-60,36,-12,-14,64,-44,12,4]).fill(accent);arc(55,-2.6,-.25,3);};
  const bolt=()=>line([-12,-70,6,-30,-15,-26,16,17,-3,13,12,63],5);
  const leaf=(x:number,y:number,angle:number)=>{const c=Math.cos(angle),s=Math.sin(angle),points=[0,-32,12,-13,8,12,0,23,-8,12,-12,-13].map((v,i,a)=>i%2===0?x+v*c-a[i+1]*s:y+a[i-1]*s+v*c);g.poly(points).fill({color,alpha:.85}).stroke({color:accent,width:1});};
  const lotus=(n=7)=>{for(let i=0;i<n;i++)leaf(Math.cos(i/n*Math.PI*2)*20,Math.sin(i/n*Math.PI*2)*20,i/n*Math.PI*2+Math.PI/2);g.circle(0,0,9).fill(accent);};
  const shield=()=>g.poly([-33,-40,0,-52,33,-40,29,15,0,43,-29,15]).fill({color,alpha:.15}).stroke({color:accent,width:3});
  const hex=()=>g.poly([-27,-47,27,-47,54,0,27,47,-27,47,-54,0]).stroke({color:accent,width:3});
  const wing=()=>{for(const s of [-1,1])for(let i=0;i<4;i++)line([s*8,15,s*(21+i*10),-25+i*11,s*(53+i*8),-43+i*14],4);};
  const eye=()=>{g.ellipse(0,0,44,20).stroke({color:accent,width:3});g.ellipse(0,0,7,17).fill(accent);};
  const dragon=()=>{line([-57,28,-32,43,10,34,37,5,34,-26,12,-43,-14,-33,-9,-9,11,-14,23,-5],7);line([12,-43,16,-58,23,-39,40,-44,34,-26],3);g.circle(19,-26,3).fill(0xffffff);};
  const flame=()=>{g.poly([-27,35,-34,7,-14,-18,-20,-50,4,-27,18,-58,20,-14,38,9,24,37,0,48]).fill({color,alpha:.7}).stroke({color:accent,width:2});g.poly([-9,33,-13,7,4,-16,6,6,19,22,8,39]).fill(accent);};
  const moon=()=>g.arc(0,0,39,.65,5.3).stroke({color:accent,width:12,cap:'round'});
  const wave=()=>{for(let i=0;i<3;i++)line([-57,10+i*12,-25,-4+i*12,10,5+i*12,45,-11+i*12,62,-3+i*12],3);};
  switch(kind){
    case 'mountain': case 'mountainShield': g.poly([-65,39,-32,-46,-5,-9,23,-65,65,39]).fill({color,alpha:.35}).stroke({color:accent,width:3});if(kind==='mountainShield')shield();break;
    case 'fault': for(let i=0;i<5;i++)shard((i-2)*24,25-Math.abs(i-2)*5,1+phase*.8);line([-85,50,-43,35,-13,46,26,29,83,45],4);break;
    case 'dragon': dragon();break;
    case 'dragonWave': dragon();wave();break;
    case 'jadeWard': shield();dragon();ring(65,color,2);break;
    case 'tiger': case 'tigerWard': g.poly([-36,20,-43,-36,-17,-20,18,-20,41,-36,36,21,0,43]).stroke({color:accent,width:3});line([-23,-5,-8,2,0,17,10,3,24,-6],4);if(kind==='tigerWard')ring(61);break;
    case 'tigerRush': for(let i=0;i<3;i++)line([-64+i*18,36,15+i*18,-39],5);wing();break;
    case 'shell': case 'shellDome': hex();for(let i=0;i<6;i++){const a=i*Math.PI/3;line([Math.cos(a)*25,Math.sin(a)*25,Math.cos(a)*54,Math.sin(a)*54],2);}ring(25);if(kind==='shellDome')ring(73,color,5);break;
    case 'turtleBreath': hex();wave();break;
    case 'dragonSlash': dragon();slash();break;
    case 'dragonDance': for(let i=0;i<3;i++)g.arc(0,0,32+i*18,i*.8-3,i*.8).stroke({color:i%2?color:accent,width:5});dragon();break;
    case 'thunderCut': bolt();slash();break;
    case 'thunderWard': shield();ring(64);bolt();break;
    case 'armorSplit': g.poly([-40,-36,-3,-45,-10,-9,0,0,-19,44,-39,11]).stroke({color:accent,width:3});g.poly([12,-46,45,-33,38,15,5,46,18,7,4,-6]).stroke({color:accent,width:3});slash();break;
    case 'banner': case 'warBanner': line([-26,54,-26,-62],5);g.poly([-25,-57,45,-49,29,-21,48,5,-25,-3]).fill({color,alpha:.6}).stroke({color:accent,width:2});if(kind==='warBanner')rays(8,60,13);break;
    case 'foxCut': flame();slash();break;
    case 'foxSpiral': for(let i=0;i<5;i++)g.arc(0,0,22+i*10,i*.9,i*.9+2.3).stroke({color:i%2?accent:color,width:5});break;
    case 'cat': g.poly([-37,24,-38,-37,-14,-15,16,-15,39,-40,36,23]).stroke({color:accent,width:3});line([-22,0,-9,3,9,3,23,-1],4);break;
    case 'shadowStep': for(let i=0;i<3;i++)g.ellipse(-i*26,0,18,46-i*6).fill({color,alpha:.4-i*.1}).stroke({color:accent,width:1});slash();break;
    case 'nightExecute': moon();slash();line([-45,-40,45,40],5);break;
    case 'blood': case 'bloodSeal': ring(44,color,5);g.poly([0,-39,35,25,-35,25]).stroke({color:accent,width:2});if(kind==='bloodSeal'){ring(60,accent,2);rays(3,46,24);}break;
    case 'bloodEclipse': g.circle(0,0,37).fill({color:0x261123,alpha:.8});moon();slash();break;
    case 'ghostBlades': for(let i=-1;i<=1;i++)g.poly([i*30-7,33,i*30-5,-19,i*30+5,-43,i*30+7,22]).fill(accent);break;
    case 'silentStrike': slash();ring(37);line([-28,-28,28,28],4);break;
    case 'cloudPierce': line([-85,0,70,0],6);g.poly([87,0,53,-16,60,0,53,16]).fill(accent);wave();break;
    case 'arrowRain': for(let i=0;i<5;i++){const x=(i-2)*24,y=i%2*23;line([x-16,y-65,x+12,y+25],3);g.poly([x+15,y+37,x+4,y+18,x+17,y+17]).fill(accent);}break;
    case 'featherVolley': for(let i=-1;i<=1;i++)leaf(i*25,0,.55);break;
    case 'eagleSight': eye();wing();ring(61,color,2);break;
    case 'solarBlast': ring(22,accent,8);ring(49,color,6);rays(12,54,26);break;
    case 'solarEclipse': g.circle(0,0,37).fill(0x1b2538);ring(40,accent,7);rays(8,49,20);break;
    case 'frostSpear': shard(0,0,2.2);for(let i=-1;i<=1;i++)shard(i*26,24,.7);break;
    case 'frostPrison': for(let i=0;i<5;i++)shard((i-2)*22,20,1.4-Math.abs(i-2)*.2);ring(62,accent,2);break;
    case 'starChain': bolt();rays(6,12,27);break;
    case 'heavenBolt': line([0,-230,-21,-120,17,-125,-11,-20,10,10],9);ring(43,accent,4);rays(9,47,25);break;
    case 'phoenixBall': flame();wing();break;
    case 'phoenixRain': for(let i=-1;i<=1;i++){line([i*45+32,-110,i*45,12],5);shard(i*45,22,1.2);}flame();break;
    case 'moonSong': moon();for(let i=0;i<3;i++)g.ellipse(0,38+i*17,42+i*13,10).stroke({color:accent,width:2});break;
    case 'moonWard': shield();moon();ring(66,color,3);break;
    case 'lotusBloom': lotus();g.ellipse(0,47,65,16).stroke({color:accent,width:3});break;
    case 'pureLotus': lotus(5);rays(10,51,14);ring(70,0xe9ffff,2);break;
    case 'tailwind': wave();leaf(-25,-16,.9);leaf(22,-30,.9);break;
    case 'headwind': for(let i=0;i<4;i++)g.arc(0,0,25+i*16,-2.8+i*.35,.4+i*.35).stroke({color:accent,width:3});leaf(30,20,-.7);break;
    case 'bolt': case 'lightning': case 'thunderOrb': bolt();break;
    case 'snow': for(let i=0;i<3;i++){const a=i*Math.PI/3;line([-Math.cos(a)*47,-Math.sin(a)*47,Math.cos(a)*47,Math.sin(a)*47],3);}rays(6,22,10);break;
    case 'sun': case 'star': ring(24);rays(kind==='sun'?12:5,28,22);break;
    case 'flame': case 'fireball': case 'dragonFlame': case 'foxFlame': case 'meteor': flame();break;
    case 'phoenix': wing();flame();break;
    case 'lotus': lotus();break;
    case 'moon': case 'moonArc': case 'bloodCrescent': moon();break;
    case 'wing': wing();break;
    case 'eye': eye();break;
    case 'petal': case 'feather': case 'windFeather': leaf(0,0,Math.PI/2);line([-24,0,23,0],2);break;
    case 'arrow': case 'rainArrow': case 'featherArrow': case 'solarArrow': case 'eclipseArrow': line([-32,0,25,0],3);g.poly([39,0,20,-9,23,0,20,9]).fill(accent);line([-23,-8,-13,0,-23,8],3);if(kind==='featherArrow')leaf(-22,0,Math.PI/2);if(kind==='solarArrow'||kind==='eclipseArrow')ring(15,accent,3);break;
    case 'ice': case 'frostBolt': case 'frostOrb': shard(0,0,1.2);break;
    case 'blade': case 'dagger': case 'shadowDagger': case 'spectralDagger': case 'goldBlade': g.poly([-33,-5,12,-6,40,0,12,6,-33,5,-25,0]).fill(accent);line([-18,-12,-18,12],3);break;
    case 'claw': for(let i=0;i<3;i++)line([-35+i*16,26,18+i*16,-29],3);break;
    case 'slash': slash();break;
    case 'wave': case 'jadePulse': wave();break;
    case 'shield': shield();break;
    case 'hexagon': hex();break;
    case 'stone': for(let i=-1;i<=1;i++)shard(i*22,0,.65);break;
    case 'scorch': case 'crater': line([-64,4,-35,-10,-13,5,15,-15,39,4,62,-7],3,color);arc(57,.1,2.9,2);break;
    case 'frost': ring(55);rays(6,25,30);break;
    case 'smoke': case 'shadow': for(let i=0;i<3;i++)g.ellipse((i-1)*21,0,24,38).fill({color,alpha:.2});break;
    default: ring(38);rays(6,44,11);break;
  }
}
