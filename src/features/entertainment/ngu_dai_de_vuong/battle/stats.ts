import type { Actor } from './types';
import type { StatusKind } from '../types';
import { BATTLE } from '../data/config';
export const clamp = (n: number, min: number, max: number) => Math.max(min, Math.min(max, n));
export const distance = (a: { x: number; y: number }, b: { x: number; y: number }) => Math.hypot(a.x - b.x, a.y - b.y);
export const modifier = (a: Actor, kind: StatusKind) => a.statuses.filter(s => s.kind === kind && s.remaining > 0).reduce((sum, s) => sum + s.value, 0);
export const has = (a: Actor, kind: StatusKind) => a.statuses.some(s => s.kind === kind && s.remaining > 0);
export const hardCC = (a: Actor) => ['stun', 'freeze', 'knockback', 'knockup'].some(kind => has(a, kind as StatusKind));
export const valid = (a: Actor | undefined): a is Actor => Boolean(a && a.hp > 0 && !has(a, 'untargetable'));
export const attack = (a: Actor) => Math.max(1, a.stats.atk * Math.max(.1, 1 + modifier(a, 'atk')));
export const interval = (a: Actor) => clamp((a.boss?.attackInterval ?? 1) / Math.max(.1, 1 + modifier(a, 'attackSpeed')), BATTLE.minInterval, BATTLE.maxInterval);
export const resistanceMultiplier = (r: number) => r >= 0 ? 100 / (100 + r) : 2 - 100 / (100 - r);
export const hpRatio = (a: Actor) => a.hp / a.stats.hp;
export const shieldTotal = (a: Actor) => modifier(a, 'shield');
export const isDebuff = (s: { kind: StatusKind; value: number }) => ['taunt', 'stun', 'freeze', 'silence', 'knockback', 'knockup', 'burn', 'mark', 'damageDown'].includes(s.kind) || (['attackSpeed', 'moveSpeed', 'atk', 'armor', 'armorPct', 'mr'].includes(s.kind) && s.value < 0);
